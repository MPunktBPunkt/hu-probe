# Generates firmware/src/media/CoverJpegs.cpp: four 320x320 baseline JPEG covers
# (PiDrive M2: JPEG 320x320 <= 8 KiB is shown by the NBT). Windows PowerShell / pwsh on Windows.
#   pwsh -File firmware/scripts/gen_covers.ps1
param([int]$Quality = 60, [int]$MaxBytes = 8192)

Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$outCpp = Join-Path $root 'src/media/CoverJpegs.cpp'

$covers = @(
    @{ N = 1; Bg = [System.Drawing.Color]::FromArgb(200, 30, 30) },
    @{ N = 2; Bg = [System.Drawing.Color]::FromArgb(30, 140, 40) },
    @{ N = 3; Bg = [System.Drawing.Color]::FromArgb(30, 60, 190) },
    @{ N = 4; Bg = [System.Drawing.Color]::FromArgb(220, 160, 0) }
)

$codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$blobs = @()
foreach ($c in $covers) {
    $q = $Quality
    while ($true) {
        $bmp = New-Object System.Drawing.Bitmap 320, 320
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.SmoothingMode = 'AntiAlias'
        $g.TextRenderingHint = 'AntiAlias'
        $g.Clear($c.Bg)
        $white = [System.Drawing.Brushes]::White
        $fmt = New-Object System.Drawing.StringFormat
        $fmt.Alignment = 'Center'; $fmt.LineAlignment = 'Center'
        $g.DrawString([string]$c.N, (New-Object System.Drawing.Font 'Arial', 150, ([System.Drawing.FontStyle]::Bold)), $white, (New-Object System.Drawing.RectangleF 0, 10, 320, 240), $fmt)
        $g.DrawString('HU-PROBE COVER', (New-Object System.Drawing.Font 'Arial', 20, ([System.Drawing.FontStyle]::Bold)), $white, (New-Object System.Drawing.RectangleF 0, 250, 320, 50), $fmt)
        $g.Dispose()
        $ep = New-Object System.Drawing.Imaging.EncoderParameters 1
        $ep.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality), ([long]$q)
        $ms = New-Object System.IO.MemoryStream
        $bmp.Save($ms, $codec, $ep)
        $bmp.Dispose()
        $bytes = $ms.ToArray()
        if ($bytes.Length -le $MaxBytes -or $q -le 20) { break }
        $q -= 10
    }
    Write-Host ("cover {0}: {1} bytes (q={2})" -f $c.N, $bytes.Length, $q)
    $blobs += , $bytes
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by firmware/scripts/gen_covers.ps1 - do not edit.')
[void]$sb.AppendLine('#include "media/CoverJpegs.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace {')
for ($i = 0; $i -lt $blobs.Count; $i++) {
    $b = $blobs[$i]
    [void]$sb.AppendLine(("const uint8_t kCover{0}[{1}] = {{" -f ($i + 1), $b.Length))
    for ($o = 0; $o -lt $b.Length; $o += 16) {
        $line = ($b[$o..([Math]::Min($o + 15, $b.Length - 1))] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
        [void]$sb.AppendLine("    $line,")
    }
    [void]$sb.AppendLine('};')
}
[void]$sb.AppendLine('}  // namespace')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace CoverJpegs {')
[void]$sb.AppendLine('const Cover kCovers[kCount] = {')
for ($i = 0; $i -lt $blobs.Count; $i++) {
    [void]$sb.AppendLine(("    {{kCover{0}, sizeof(kCover{0})}}," -f ($i + 1)))
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('}  // namespace CoverJpegs')
[System.IO.File]::WriteAllText($outCpp, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "wrote $outCpp"
